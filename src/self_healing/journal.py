"""Turn evidence/run_journal.jsonl and run_history.json into a results report.

The classifier is told to reply with a strict format but does not always hold
it, so its category is extracted with a regex instead of trusting the model's
formatting (see docs/adr/0002-deterministic-extraction-fallback.md).

Usage: python -m self_healing.journal > docs/results.md
"""

from __future__ import annotations

import json
import re
from datetime import datetime
from pathlib import Path
from statistics import median
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]

CATEGORIES = {"schema_drift", "null_violation", "oom", "bad_join", "type_mismatch", "unclassified"}
_LABEL = re.compile(r"\b(?:Classification|Category)\s*[:\-–—]+\s*([a-z_]+)", re.IGNORECASE)
_CLAUSE = re.compile(r"\bContract clause\s*:\s*([\w.]+)", re.IGNORECASE)
_TARGET = re.compile(r"\bTarget\s*:\s*\S*?(\w+)\.py")
_STATE = re.compile(r'state\\?"\s*:\s*\\?"(\w+)')


def parse_classification(raw_output: str) -> str:
    """Return the taxonomy category named in a classifier reply, or raise ValueError."""
    match = _LABEL.search(raw_output.replace("*", "").replace("`", ""))
    if match and match.group(1).lower() in CATEGORIES:
        return match.group(1).lower()
    raise ValueError("classifier output has no Classification/Category label naming a known category")


def _seconds_between(start: str, end: str) -> int:
    return int((datetime.fromisoformat(end) - datetime.fromisoformat(start)).total_seconds())


def _tool(row: dict[str, Any]) -> str:
    return row.get("tool_name", "").rsplit("__", 1)[-1]


def build_rounds(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Group journal rows into diagnostic rounds, each starting at a log-parser completion."""
    rounds: list[dict[str, Any]] = []
    for row in rows:
        agent, tool, output = row.get("agent_name"), _tool(row), row["output"]
        if agent == "log-parser":
            rounds.append(
                {
                    "started": row["timestamp"],
                    "scenario": None,
                    "category": "unparsed",
                    "clause": None,
                    "diagnosis_s": None,
                    "applied": False,
                    "outcome": None,
                    "verify_s": None,
                }
            )
        elif not rounds:
            continue
        elif agent == "classifier":
            try:
                rounds[-1]["category"] = parse_classification(output)
            except ValueError:
                pass
            clause = _CLAUSE.search(output)
            rounds[-1]["clause"] = clause.group(1) if clause and clause.group(1) != "none" else None
        elif agent == "patch-proposer":
            target = _TARGET.search(output)
            rounds[-1]["scenario"] = target.group(1) if target else None
            rounds[-1]["diagnosis_s"] = _seconds_between(rounds[-1]["started"], row["timestamp"])
        elif tool == "apply_patch":
            rounds[-1]["applied"] = True
        elif tool == "run_job" and rounds[-1]["applied"] and rounds[-1]["outcome"] is None:
            state = _STATE.search(output)
            rounds[-1]["outcome"] = state.group(1) if state else "UNKNOWN"
            rounds[-1]["verify_s"] = _seconds_between(rounds[-1]["started"], row["timestamp"])
    return rounds


def summarize_runtimes(history: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    """Per job: the last failure before the first success, that success, and the latest run."""
    jobs: dict[str, list[dict[str, Any]]] = {}
    for run in sorted(history, key=lambda r: r["start_time"]):
        jobs.setdefault(run["job_name"], []).append(run)

    summary = {}
    for name, runs in jobs.items():
        first_success = next((i for i, r in enumerate(runs) if r["result_state"] == "SUCCESS"), None)
        failures = [r for r in runs[:first_success] if r["result_state"] == "FAILED"]
        summary[name] = {
            "failed_s": failures[-1]["run_duration_s"] if failures else None,
            "fixed_s": runs[first_success]["run_duration_s"] if first_success is not None and failures else None,
            "latest_state": runs[-1]["result_state"],
            "latest_s": runs[-1]["run_duration_s"],
        }
    return summary


def _cell(value: Any, suffix: str = "") -> str:
    return "n/a" if value is None else f"{value}{suffix}"


def render(rounds: list[dict[str, Any]], runtimes: dict[str, dict[str, Any]]) -> str:
    """Render the report as Markdown."""
    verified = sum(r["outcome"] == "SUCCESS" for r in rounds)
    diagnosis = [r["diagnosis_s"] for r in rounds if r["diagnosis_s"] is not None]
    lines = [
        "# Results",
        "",
        "Generated by `make report` from `evidence/run_journal.jsonl` and `evidence/run_history.json`.",
        "",
        f"- Diagnostic rounds: **{len(rounds)}**",
        f"- Patches applied: **{sum(r['applied'] for r in rounds)}**",
        f"- Patches verified by a successful re-run: **{verified}**",
        f"- Median diagnosis time: **{_cell(int(median(diagnosis)) if diagnosis else None, ' s')}**",
        "",
        "Diagnosis time runs from log-parser finishing to patch-proposer finishing. "
        "Time to verify runs from log-parser finishing to the re-run completing, including human review.",
        "",
        "## Diagnostic rounds",
        "",
        "| Started (UTC) | Scenario | Category | Contract clause | Diagnosis | Applied | Re-run | Time to verify |",
        "|---|---|---|---|---:|---|---|---:|",
    ]
    for r in rounds:
        lines.append(
            f"| {r['started']} | {_cell(r['scenario'])} | `{r['category']}` | {_cell(r['clause'])} "
            f"| {_cell(r['diagnosis_s'], ' s')} | {'yes' if r['applied'] else 'no'} | {_cell(r['outcome'])} "
            f"| {_cell(r['verify_s'], ' s')} |"
        )
    lines += [
        "",
        "## Job runtimes",
        "",
        "| Job | Last failure before first success | First success | Latest run |",
        "|---|---:|---:|---|",
    ]
    for name, s in sorted(runtimes.items()):
        lines.append(
            f"| `{name}` | {_cell(s['failed_s'], ' s')} | {_cell(s['fixed_s'], ' s')} "
            f"| {_cell(s['latest_state'])}, {s['latest_s']} s |"
        )
    return "\n".join(lines)


def main() -> None:
    """Print the report for the evidence committed in this repo."""
    journal = (REPO_ROOT / "evidence" / "run_journal.jsonl").read_text().splitlines()
    history = json.loads((REPO_ROOT / "evidence" / "run_history.json").read_text())
    print(render(build_rounds([json.loads(line) for line in journal]), summarize_runtimes(history)))


if __name__ == "__main__":
    main()
